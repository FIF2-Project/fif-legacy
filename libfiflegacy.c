static int fifq_decode_ftc3(const uint8_t *f, size_t len, const char *path, fifq_image *img, fifq_stats *st) {
    fifq_ftc3 *h = (fifq_ftc3 *)calloc(1, sizeof(fifq_ftc3));
    int err = FIF_ERR_MALFORMED, i, CW = 0, CH = 0;
    uint8_t *canvas = NULL, *fttbuf = NULL;
    fifq_ftt ftt;
    size_t pos;
    if (!h) return FIF_ERR_MEMORY;
    err = fifq_ftc3_header(f, len, h);
    if (err) goto done;
    err = FIF_ERR_MALFORMED;
    for (i = 0; i < h->nreg; i++) {
        if (h->rx[i] + h->rw[i] > CW) CW = h->rx[i] + h->rw[i];
        if (h->ry[i] + h->rh[i] > CH) CH = h->ry[i] + h->rh[i];
    }
    ftt.pix = NULL; ftt.w = ftt.h = 0;
    if ((int64_t)CW * CH > FIFQ_MAXPIX / 2) { err = FIF_ERR_TOO_LARGE; goto done; }
    canvas = (uint8_t *)calloc((size_t)CW * (h->color ? CH * 3 / 2 : CH), 1);
    if (!canvas) { err = FIF_ERR_MEMORY; goto done; }
    pos = h->payload_off;
    for (i = 0; i < h->nreg; i++) {
        int RW = h->rw[i], RH = h->rh[i], PH = h->color ? RH * 3 / 2 : RH, ok, y, x, needext = 0;
        uint32_t L;
        size_t k, nrec = (size_t)(RW / 4) * (PH / 4);
        fifq_rec *rec;
        uint8_t *full;
        if (pos + 4 > h->payload_off + h->payload_size) goto done;
        L = fifq_u32(f + pos);
        if (!L || L > h->payload_off + h->payload_size - pos - 4) goto done;
        rec = (fifq_rec *)calloc(nrec, sizeof(fifq_rec));
        full = (uint8_t *)malloc((size_t)RW * PH);
        if (!rec || !full) { free(rec); free(full); err = FIF_ERR_MEMORY; goto done; }
        if (h->entropy == 1) ok = fifq_ftc3_region_p1(h, f + pos + 4, L, RW, RH, rec, h->nftt, st);
        else ok = fifq_ftc3_region_p2(h, f + pos + 4, L, RW, RH, rec, st);
        if (ok < 0) { free(rec); free(full); err = FIF_ERR_UNSUPPORTED; goto done; }
        for (k = 0; ok && k < nrec; k++) { if (!rec[k].set) ok = 0; if (rec[k].ext) needext = 1; }
        if (ok && needext && !ftt.pix) {
            int e2 = 0;
            fttbuf = fifq_load_ftt(path, h, &e2);
            if (!fttbuf) { free(rec); free(full); err = e2; goto done; }
            ftt.pix = fttbuf + 26; ftt.w = (int)h->ftt_w; ftt.h = (int)h->ftt_h;
        }
        if (ok) ok = fifq_ftc_reconstruct(rec, RW, PH, &ftt, full, st);
        if (ok && FIFQ_ENHANCED) ok = fifq_ftc_refine(rec, RW, PH, full);
        if (ok) ok = fifq_ftc_filter(rec, RW, PH, RH / 4, h->color, full);
        if (ok && FIFQ_ENHANCED) fifq_ftc_deblock(RW, RH, h->color, h->qstep8 >= 24, full);
        if (ok && st) st->regions++;
        if (ok) {
            for (y = 0; y < RH; y++) memcpy(canvas + (size_t)(h->ry[i] + y) * CW + h->rx[i], full + (size_t)y * RW, (size_t)RW);
            if (h->color) for (y = 0; y < RH / 2; y++) for (x = 0; x < RW / 2; x++) {
                uint8_t *crow = canvas + (size_t)CH * CW + (size_t)(h->ry[i] / 2 + y) * CW;
                const uint8_t *srow = full + (size_t)(RH + y) * RW;
                crow[h->rx[i] / 2 + x] = srow[x];
                crow[CW / 2 + h->rx[i] / 2 + x] = srow[RW / 2 + x];
            }
        }
        free(rec); free(full);
        if (!ok) goto done;
        pos += 4 + L;
    }
    if (pos != h->payload_off + h->payload_size) goto done;
    img->w = h->outw; img->h = h->outh;
    img->rgb = (uint8_t *)malloc((size_t)img->w * img->h * 3);
    if (!img->rgb) { err = FIF_ERR_MEMORY; goto done; }
    fifq_to_rgb(canvas, CW, CH, h->color, 0, 0, img);
    err = 0;
done:
    free(canvas); free(fttbuf); free(h);
    return err;
}

/* ---- external Fractal Transform Template (FTT) loader ---- */
static uint8_t *fifq_try_read(const char *path, size_t *n) {
    FILE *fp = fopen(path, "rb");
    uint8_t *d = NULL;
    long l;
    if (!fp) return NULL;
    if (fseek(fp, 0, SEEK_END) == 0 && (l = ftell(fp)) > 0 && l < 0x10000000L && fseek(fp, 0, SEEK_SET) == 0) {
        d = (uint8_t *)malloc((size_t)l);
        if (d && fread(d, 1, (size_t)l, fp) != (size_t)l) { free(d); d = NULL; }
        else if (d) *n = (size_t)l;
    }
    fclose(fp);
    return d;
}

static uint8_t *fifq_load_ftt(const char *fifpath, const fifq_ftc3 *h, int *err) {
    const char *base = h->ftt_name, *s;
    size_t dirlen = 0, i, n = 0;
    char *cand;
    int variant;
    for (s = h->ftt_name; *s; s++) if (*s == '\\' || *s == '/' || *s == ':') base = s + 1;
    for (i = 0; fifpath[i]; i++) if (fifpath[i] == '/' || fifpath[i] == '\\') dirlen = i + 1;
    *err = FIF_ERR_FTT_MISSING;
    if (!*base) return NULL;
    cand = (char *)malloc(dirlen + strlen(base) + 1);
    if (!cand) { *err = FIF_ERR_MEMORY; return NULL; }
    for (variant = 0; variant < 3; variant++) {       /* case-insensitive basename match */
        uint8_t *d;
        memcpy(cand, fifpath, dirlen);
        for (i = 0; base[i]; i++) {
            char c = base[i];
            if (variant == 1 && c >= 'A' && c <= 'Z') c = (char)(c - 'A' + 'a');
            if (variant == 2 && c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
            cand[dirlen + i] = c;
        }
        cand[dirlen + i] = 0;
        d = fifq_try_read(cand, &n);
        if (!d) continue;
        if (n >= 26 && !memcmp(d, "FTT\0", 4) && !fifq_u16(d + 4) && fifq_u16(d + 6) == 0x0101 &&
            fifq_u16(d + 8) == h->ftt_w && fifq_u16(d + 10) == h->ftt_h && fifq_u16(d + 12) == 8 &&
            !fifq_u16(d + 14) && fifq_u16(d + 16) == 26 && fifq_u32(d + 18) == (uint32_t)h->ftt_w * h->ftt_h &&
            fifq_u32(d + 22) == h->ftt_id && n == 26u + (size_t)h->ftt_w * h->ftt_h) {
            free(cand);
            return d;
        }
        free(d);
        *err = FIF_ERR_MALFORMED;
        break;
    }
    free(cand);
    return NULL;
}

/* ---- Profile-2 arithmetic entropy (24-bit range coder) ---- */
typedef struct {
    const uint8_t *d;
    size_t n, p;
    uint64_t code, interval;
    int err;
} fifq_rc;

static void fifq_rc_byte(fifq_rc *r) {
    unsigned v = 0;
    if (r->p < r->n) v = r->d[r->p];
    else r->err = 1;                          /* FTC streams never receive implicit bytes */
    r->p++;
    r->code = (r->code << 8) | v;
}
static void fifq_rc_init(fifq_rc *r, const uint8_t *d, size_t n) {
    r->d = d; r->n = n; r->p = 0; r->code = 0; r->err = 0;
    fifq_rc_byte(r); fifq_rc_byte(r); fifq_rc_byte(r);
    r->interval = 0x1000000u;
}
/* cum: descending cumulative array of C+1 entries, cum[0]=0x4000, cum[C]=0 */
static int fifq_rc_dec(fifq_rc *r, const uint32_t *cum, int C) {
    int lo = 0, hi = C - 1, i;
    uint64_t a, b;
    if (r->err) return 0;
    while (lo < hi) {                          /* smallest i with f(i+1) <= code */
        int mid = (lo + hi) / 2;
        if (((r->interval * cum[mid + 1]) >> 14) <= r->code) hi = mid; else lo = mid + 1;
    }
    i = lo;
    a = (r->interval * cum[i + 1]) >> 14;
    b = (r->interval * cum[i]) >> 14;
    if (!(a <= r->code && r->code < b)) { r->err = 1; return 0; }
    r->code -= a;
    r->interval = b - a;
    while (r->interval < 0x8000u) { r->interval <<= 8; fifq_rc_byte(r); }
    return i;
}
static int fifq_rc_uni(fifq_rc *r, int n) {
    uint32_t cum[17];
    int i;
    for (i = 0; i <= n; i++) cum[i] = (uint32_t)(0x4000 * (n - i) / n);
    return fifq_rc_dec(r, cum, n);
}
static int fifq_rc_norm(const int64_t *w, int C, uint32_t *cum) {
    int64_t tot = 0, acc;
    int i;
    for (i = 0; i < C; i++) tot += w[i];
    if (tot <= 0) return 0;
    acc = tot;
    for (i = 0; i < C; i++) { cum[i] = (uint32_t)((acc * 0x4000) / tot); acc -= w[i]; }
    cum[C] = 0;
    return 1;
}
static int fifq_sgn(int64_t v) { return v > 0 ? 1 : (v < 0 ? -1 : 0); }

/* transmitted model of C symbols -> cum (C+1 entries) */
static int fifq_rc_model(fifq_rc *r, int C, uint32_t *cum) {
    int64_t *w = (int64_t *)malloc(sizeof(int64_t) * (size_t)C);
    int i, ok;
    if (!w) return 0;
    if (C < 32) {
        for (i = 0; i < C; i++) { int v = fifq_rc_uni(r, 16); w[i] = (int64_t)v * v; }
    } else {
        int64_t aw[4], prev = 0, delta = 1;
        uint32_t acum[5];
        for (i = 0; i < 4; i++) aw[i] = fifq_rc_uni(r, 16);
        if (!fifq_rc_norm(aw, 4, acum)) { free(w); return 0; }
        for (i = 0; i < C; i++) {
            int a = fifq_rc_dec(r, acum, 4);
            int64_t nw;
            if (prev == 0) {
                static const int start[4] = {0, 1, 4, 12};
                nw = delta = start[a];
            } else {
                if (a == 1) delta = (-fifq_sgn(delta) - delta) / 2;
                else if (a == 2) delta = (fifq_sgn(delta) + delta) / 2;
                else if (a == 3) delta *= 2;
                if (delta > ((int64_t)1 << 36) || delta < -((int64_t)1 << 36)) { free(w); return 0; }
                nw = prev + delta;
                if (nw < 0) nw = 0;
                if (nw > ((int64_t)1 << 36)) { free(w); return 0; }
            }
            w[i] = nw;
            prev = nw;
        }
    }
    ok = !r->err && fifq_rc_norm(w, C, cum);
    free(w);
    return ok;
}

/* one plane of the arithmetic profile */
static int fifq_p2_plane(fifq_rc *r, fifq_ftc3 *h, const fifq_plane *pl, fifq_rec *rec, int hw, int hh, fifq_stats *st, int pidx) {
    int pbw = (pl->bw + 3) & ~3, pbh = (pl->bh + 3) & ~3;
    int nord = pbw * pbh, ntx = pbw / 4, ntiles = nord / 16, o, t, ngroups = 0, ok = 0, flag, f, g;
    int32_t *cell = (int32_t *)malloc(sizeof(int32_t) * (size_t)(nord ? nord : 1));
    uint8_t *cls = (uint8_t *)malloc((size_t)(nord ? nord : 1));
    int32_t *gbase = (int32_t *)malloc(sizeof(int32_t) * (size_t)(nord ? nord : 1));
    uint8_t *gsize = (uint8_t *)malloc((size_t)(nord ? nord : 1));
    int *val[6] = {NULL, NULL, NULL, NULL, NULL, NULL};
    int ncum = (pl->dcols > pl->drows ? pl->dcols : pl->drows) + 4100;
    uint32_t *cum = (uint32_t *)malloc(sizeof(uint32_t) * (size_t)ncum);
    uint32_t cumK[17], cumZ[17];
    if (!cell || !cls || !gbase || !gsize || !cum) goto done;
    for (o = 0; o < nord; o++) {
        int tile = o / 16, i = o % 16;
        int row = (tile / ntx) * 4 + fifq_ord_row[i], col = (tile % ntx) * 4 + fifq_ord_col[i];
        cell[o] = (row < pl->bh && col < pl->bw) ? (pl->row0 + row) * (int32_t)pl->bw + col : -1;
    }
    /* --- classification --- */
    flag = fifq_rc_uni(r, 4);
    if (flag & 1) { ok = -1; goto done; }        /* dictionary classes need an FTT: unsupported */
    if (!fifq_rc_model(r, 16, cumK) || !fifq_rc_model(r, 16, cumZ)) goto done;
    for (t = 0; t < ntiles; t++) {
        int q, k = 0;
        if (!(flag & 2)) k = fifq_rc_dec(r, cumK, 16);
        for (q = 0; q < 4; q++) {
            int kq = (flag & 2) ? fifq_rc_dec(r, cumK, 16) : 0;
            int z = fifq_rc_dec(r, cumZ, 16), j;
            for (j = 0; j < 4; j++) {
                int oo = t * 16 + q * 4 + j, two;
                two = (flag & 2) ? ((kq >> j) & 1) : ((k >> q) & 1);
                cls[oo] = (uint8_t)(((z >> j) & 1) ? 0 : (two ? 2 : 1));
            }
        }
    }
    if (r->err) goto done;
    if (st) for (o = 0; o < nord; o++) if (cell[o] >= 0) st->cells[pidx][cls[o] & 7]++;
    /* groups: class 2 (tiles), class 1 (quads), class 0 (cells) */
    for (g = 2; g >= 0; g--) {
        int gs = g == 2 ? 16 : (g == 1 ? 4 : 1), b2;
        for (b2 = 0; b2 < nord; b2 += gs) {
            int k, any = 0;
            for (k = 0; k < gs; k++) if (cell[b2 + k] >= 0 && cls[b2 + k] == g) { any = 1; break; }
            if (any) { gbase[ngroups] = b2; gsize[ngroups] = (uint8_t)g; ngroups++; if (st) st->recs[pidx][g]++; }
        }
    }
    for (f = 0; f < 6; f++) {
        val[f] = (int *)calloc((size_t)(ngroups ? ngroups : 1), sizeof(int));
        if (!val[f]) goto done;
    }
    /* --- columnar fields: selector, high quant bits, low part, symmetry, domain x, domain y --- */
    {
        int bits = h->P.qbits[0], hb = bits > 9 ? 9 : bits, lb = bits - hb, i;
        if (h->P.nq == 2) {
            if (!fifq_rc_model(r, 2, cum)) goto done;
            for (i = 0; i < ngroups; i++) val[0][i] = fifq_rc_dec(r, cum, 2);
        }
        if (!fifq_rc_model(r, 1 << hb, cum)) goto done;
        for (i = 0; i < ngroups; i++) val[1][i] = fifq_rc_dec(r, cum, 1 << hb);
        if (lb > 0) {
            if (!fifq_rc_model(r, 1 << lb, cum)) goto done;
            for (i = 0; i < ngroups; i++) val[2][i] = fifq_rc_dec(r, cum, 1 << lb);
        }
        if (!fifq_rc_model(r, 8, cum)) goto done;
        for (i = 0; i < ngroups; i++) val[3][i] = fifq_rc_dec(r, cum, 8);
        for (f = 0; f < 2; f++) {
            int cnt = f == 0 ? pl->dcols : pl->drows, pred = fifq_rc_uni(r, 2);
            if (!fifq_rc_model(r, cnt, cum)) goto done;
            for (i = 0; i < ngroups; i++) {
                int v = fifq_rc_dec(r, cum, cnt);
                if (pred) {
                    int c0 = cell[gbase[i]], rc;
                    rc = f == 0 ? (c0 % pl->bw) * 4 : (c0 / pl->bw - pl->row0) * 4;   /* plane-relative range coordinate */
                    v = ((rc / 2 - cnt / 2 + v) % cnt + cnt) % cnt;
                }
                val[4 + f][i] = v * 2;
            }
        }
        if (r->err) goto done;
        for (i = 0; i < ngroups; i++) {
            int sel = val[0][i], raw = (val[1][i] << lb) | val[2][i], k, gg = gsize[i];
            int gs = gg == 2 ? 16 : (gg == 1 ? 4 : 1), G = gg == 2 ? 4 : (gg == 1 ? 2 : 1);
            fifq_rec br;
            memset(&br, 0, sizeof br);
            br.q = h->P.qval[sel][raw]; br.slope = (uint8_t)h->P.qkind[sel];
            br.sym = (uint8_t)val[3][i]; br.dx = val[4][i]; br.dy = val[5][i];
            br.cls = (uint8_t)gg; br.set = 1;
            for (k = 0; k < gs; k++) {
                int oo = gbase[i] + k, sr, sc;
                fifq_rec dr = br;
                if (cell[oo] < 0 || cls[oo] != gg) continue;
                if (G > 1) {
                    fifq_sym(br.sym, fifq_ord_row[k], fifq_ord_col[k], G, &sr, &sc);
                    dr.dx += 8 * sc; dr.dy += 8 * sr;
                    if (dr.dx / 2 + 4 > hw || dr.dy / 2 + 4 > hh) goto done;
                }
                rec[cell[oo]] = dr;
            }
        }
    }
    ok = 1;
done:
    free(cell); free(cls); free(gbase); free(gsize); free(cum);
    for (f = 0; f < 6; f++) free(val[f]);
    return ok;
}

static int fifq_ftc3_region_p2(fifq_ftc3 *h, const uint8_t *s, size_t n, int RW, int RH, fifq_rec *rec, fifq_stats *st) {
    fifq_rc r;
    fifq_plane pl;
    int PH = h->color ? RH * 3 / 2 : RH, res;
    if (h->minor == 3) return -1;               /* 3.3 side channel: unsupported variant */
    if (h->P.nq == 2 && h->P.qbits[0] != h->P.qbits[1]) return -1;
    if (n < 3) return 0;
    fifq_rc_init(&r, s, n);
    pl.bw = RW / 4; pl.bh = RH / 4; pl.row0 = 0; pl.dstep = 2;
    pl.dcols = (RW + 1) / 2; pl.drows = (RH + 1) / 2;
    res = fifq_p2_plane(&r, h, &pl, rec, RW / 2, PH / 2, st, 0);
    if (res != 1) return res;
    if (h->color) {
        pl.bh = RH / 8; pl.row0 = RH / 4;
        pl.drows = (RH + 1) / 2 + (RH / 2 + 1) / 2;
        res = fifq_p2_plane(&r, h, &pl, rec, RW / 2, PH / 2, st, 1);
        if (res != 1) return res;
    }
    if (r.err || r.p > n || n - r.p > 3) return 0;
    return 1;
}

